            var body = new Panel
            {
                Location = new Point(0, 80),
                Size = new Size(900, 508),
                BackColor = UiTheme.DialogBackground
            };
            _leftCard = UiModal.Card(0, 0, 100, 100, "", "", withHeader: false);
            _rightCard = UiModal.Card(0, 0, 100, 100, "", "", withHeader: false);
            // Поиск — в общей рамке UiModal.Field (как поля в диалогах).
            _searchBox = new TextBox
            {
                Multiline = false,
                TabStop = false,
                BackColor = Color.White,
                ForeColor = UiTheme.Foreground
            };
            _searchWrap = UiModal.Field(_searchBox, 200, 30);
            _searchBox.Font = new Font("Segoe UI", 9F);
            _searchBox.HandleCreated += (s, e) => SetCue(_searchBox, "Поиск по справке…");
            _searchBox.TextChanged += (s, e) => ApplyFilter();
            _hitLabel = new Label
            {
                AutoSize = false,
                Font = new Font("Segoe UI", 8F),
                ForeColor = UiTheme.MutedForeground,
                BackColor = Color.Transparent,
                TextAlign = ContentAlignment.MiddleLeft
            };
            _contents = new ListBox
            {
                BorderStyle = BorderStyle.None,
                BackColor = Color.White,
                ForeColor = UiTheme.Foreground,
                Font = new Font("Segoe UI", 9F),
                IntegralHeight = false,
                DrawMode = DrawMode.OwnerDrawFixed,
                ItemHeight = 26
            };
            _contents.DrawItem += (s, e) =>
            {
                try
                {
                    e.DrawBackground();
                    bool sel = (e.State & DrawItemState.Selected) == DrawItemState.Selected;
                    using var b = new SolidBrush(sel ? UiTheme.AccentSoft : Color.White);
                    e.Graphics.FillRectangle(b, e.Bounds);
                    if (e.Index >= 0 && e.Index < _contents.Items.Count)
                    {
                        string t = _contents.Items[e.Index]?.ToString() ?? "";
                        TextRenderer.DrawText(e.Graphics, t, _contents.Font,
                            new Rectangle(e.Bounds.X + 10, e.Bounds.Y, e.Bounds.Width - 14, e.Bounds.Height),
                            UiTheme.Foreground,
                            TextFormatFlags.Left | TextFormatFlags.VerticalCenter
                            | TextFormatFlags.SingleLine | TextFormatFlags.EndEllipsis);
                    }
                    e.DrawFocusRectangle();
                }
                catch { }
            };
            _contents.SelectedIndexChanged += (s, e) => JumpToSelected();
            _text = new RichTextBox
            {
                ReadOnly = true,
                BorderStyle = BorderStyle.None,
                BackColor = Color.White,
                ForeColor = UiTheme.Foreground,
                Font = new Font("Segoe UI", 9F),
                WordWrap = true,
                ScrollBars = RichTextBoxScrollBars.Vertical,
                TabStop = false
            };
            // ПКМ по выделенному: копировать + добавить в закладки
            // (темированное меню показываем вручную — его пункты
            // строятся в собственном Show, назначенный ContextMenuStrip
            // остался бы пустым).
            _text.MouseUp += (s, e) =>
            {
                try
                {
                    if (e.Button != MouseButtons.Right || _text.SelectionLength <= 0) return;
                    var menu = new ThemedContextMenu();
                    menu.AddItem("Копировать", "copy", () => { try { _text.Copy(); } catch { } });
                    menu.AddItem("Добавить в закладки", "book", () => AddSelectionToBookmarks());
                    menu.Show(this, Cursor.Position);
                }
                catch { }
            };
            _leftCard.Controls.Add(_hitLabel);
            _leftCard.Controls.Add(_searchWrap);
            _leftCard.Controls.Add(_contents);
            _rightCard.Controls.Add(_text);
            body.Controls.Add(_rightCard);
            body.Controls.Add(_leftCard);
            Controls.Add(body);

            // Колесо над текстом/списком крутит именно их: WinForms шлёт
            // WM_MOUSEWHEEL сфокусированному контролу, а не тому, что под
            // курсором (фокус тут обычно в поиске — текст стоял мёртво).
            ShadowWheel.Register(_text, TextCanScroll, TextScrollLines);
            ShadowWheel.Register(_contents, ListCanScroll, ListScrollLines);

            BuildText();
            ApplyFilter();
            Resize += (s, e) => LayoutBody();
            LayoutBody();
            Shown += (s, e) =>
            {
                LayoutBody();
                try
                {
                    SetCue(_searchBox, "Поиск по справке…");
                    ApplyFilter();
                }
                catch { }
            };

            void LayoutBody()
            {
                try
                {
                    body.Width = ClientSize.Width;
                    body.Height = Math.Max(200, ClientSize.Height - 80 - 52);
                    const int m = 14;
                    const int leftW = 262;
                    _leftCard.Location = new Point(m, 12);
                    _leftCard.Size = new Size(leftW, body.Height - 24);
                    _rightCard.Location = new Point(m + leftW + 12, 12);
                    _rightCard.Size = new Size(
                        Math.Max(200, body.Width - (m + leftW + 12) - m),
                        body.Height - 24);
                    _searchWrap.Location = new Point(10, 10);
                    _searchWrap.Width = leftW - 20;
                    _hitLabel.Location = new Point(12, 10 + _searchWrap.Height + 4);
                    _hitLabel.Size = new Size(leftW - 24, 16);
                    _contents.Location = new Point(10, _hitLabel.Bottom + 6);
                    _contents.Size = new Size(leftW - 20,
                        Math.Max(60, _leftCard.Height - _contents.Top - 10));
                    _text.Location = new Point(10, 10);
                    _text.Size = new Size(_rightCard.Width - 20, _rightCard.Height - 20);
                }
                catch { }
            }
        }

        // Фильтр содержания по заголовкам и тексту (регистр не важен).
        private void ApplyFilter()
        {
            try
            {
                string q = (_searchBox.Text ?? "").Trim();
                _shown.Clear();
                _contents.BeginUpdate();
                _contents.Items.Clear();
                for (int i = 0; i < Sections.Count; i++)
                {
                    if (q.Length == 0
                        || Sections[i].Title.Contains(q, StringComparison.OrdinalIgnoreCase)
                        || Sections[i].Body.Contains(q, StringComparison.OrdinalIgnoreCase))
                    {
                        _shown.Add(i);
                        _contents.Items.Add(Sections[i].Title);
                    }
                }
                _contents.EndUpdate();
                _hitLabel.Text = q.Length == 0
                    ? $"Разделов: {Sections.Count}"
                    : $"Найдено: {_shown.Count}";
                if (_contents.Items.Count > 0)
                    _contents.SelectedIndex = 0;
            }
            catch { }
        }

        // Колесо мыши: текст и список содержания.
        private bool TextCanScroll()
        {
            try
            {
                if (!_text.IsHandleCreated || _text.TextLength == 0) return false;
                var p = _text.GetPositionFromCharIndex(_text.TextLength - 1);
                return p.Y > _text.ClientSize.Height;
            }
            catch { return false; }
        }

        private bool TextScrollLines(int lines)
        {
            try
            {
                if (!_text.IsHandleCreated) return false;
                SendMessage(_text.Handle, EM_LINESCROLL, 0, lines);
                return true;
            }
            catch { return false; }
        }

        private bool ListCanScroll()
        {
            try
            {
                return _contents.Items.Count > 0
                    && _contents.Items.Count * _contents.ItemHeight > _contents.ClientSize.Height;
            }
            catch { return false; }
        }

        private bool ListScrollLines(int lines)
        {
            try
            {
                int n = _contents.Items.Count;
                if (n == 0) return false;
                int page = Math.Max(1, _contents.ClientSize.Height / Math.Max(1, _contents.ItemHeight));
                int max = Math.Max(0, n - page);
                _contents.TopIndex = Math.Max(0, Math.Min(max, _contents.TopIndex + lines));
                return true;
            }
            catch { return false; }
        }

        // Переход к выбранному разделу; при активном поиске первое
        // совпадение в тексте подсвечивается.
        private void JumpToSelected()
        {
            try
            {
                int i = _contents.SelectedIndex;
                if (i < 0 || i >= _shown.Count) return;
                int si = _shown[i];
                _text.SelectionStart = _starts[si];
                _text.SelectionLength = 0;
                _text.ScrollToCaret();
                string q = (_searchBox.Text ?? "").Trim();
                if (q.Length > 0)
                {
                    int bi = Sections[si].Body.IndexOf(q, StringComparison.OrdinalIgnoreCase);
                    if (bi >= 0)
                    {
                        int pos = _starts[si] + Sections[si].Title.Length + 1 + bi;
                        _text.SelectionStart = pos;
                        _text.SelectionLength = q.Length;
                        _text.ScrollToCaret();
                    }
                }
                _text.Focus();
            }
            catch { }
        }

        // Выделенное → в закладки (стор). Возвращает false, если
        // выделять было нечего. Вызывает ПКМ-меню и диалог закладок.
        private bool AddSelectionToBookmarks()
        {
            try
            {
                var bm = GetSelectedSnippet();
                if (bm == null)
                {
                    _hitLabel.Text = "Сначала выделите текст.";
                    return false;
                }
                var items = HelpBookmarkStore.Load();
                items.Add(bm);
                HelpBookmarkStore.Save(items);
                _hitLabel.Text = "Добавлено в закладки.";
                return true;
            }
            catch { return false; }
        }

        // Выделенный фрагмент для закладок: (раздел, смещение в тексте,
        // текст до 200 символов). Null — ничего не выделено.
        public HelpBookmark? GetSelectedSnippet()
        {
            try
            {
                if (_text.SelectionLength <= 0) return null;
                int pos = _text.SelectionStart;
                int si = _starts.Count - 1;
                for (int i = 0; i < _starts.Count; i++)
                    if (pos < _starts[i]) { si = Math.Max(0, i - 1); break; }
                int bodyStart = _starts[si] + Sections[si].Title.Length + 1;
                int len = Math.Min(_text.SelectionLength, 200);
                string snippet = _text.Text.Substring(
                    Math.Max(bodyStart, Math.Min(pos, _text.Text.Length)),
                    Math.Max(0, Math.Min(len, _text.Text.Length - Math.Max(bodyStart, Math.Min(pos, _text.Text.Length)))));
                if (string.IsNullOrWhiteSpace(snippet)) return null;
                return new HelpBookmark
                {
                    Section = si,
                    SectionTitle = Sections[si].Title,
                    Offset = Math.Max(0, pos - bodyStart),
                    Text = snippet.Trim(),
                    CreatedAt = DateTime.Now
                };
            }
            catch { return null; }
        }

        // Переход к закладке: снимаем фильтр, выбираем раздел, ставим
        // каретку на место и подсвечиваем фрагмент.
        public void JumpToBookmark(HelpBookmark bm)
        {
            try
            {
                if (bm == null) return;
                if (_searchBox.Text.Length > 0) _searchBox.Text = "";
                int si = bm.Section;
                if (si < 0 || si >= Sections.Count)
                {
                    si = 0;
                    for (int i = 0; i < Sections.Count; i++)
                        if (Sections[i].Title == bm.SectionTitle) { si = i; break; }
                }
                int li = _shown.IndexOf(si);
                if (li >= 0) _contents.SelectedIndex = li;
                int bodyStart = _starts[si] + Sections[si].Title.Length + 1;
                int pos = Math.Max(bodyStart, Math.Min(bodyStart + Math.Max(0, bm.Offset), _text.Text.Length));
                _text.SelectionStart = pos;
                _text.SelectionLength = Math.Max(0, Math.Min(bm.Text?.Length ?? 0, _text.Text.Length - pos));
                _text.ScrollToCaret();
                _text.Focus();
            }
            catch { }
        }

        private void BuildText()
        {
            try
            {
                var sb = new System.Text.StringBuilder();
                _starts.Clear();
                for (int i = 0; i < Sections.Count; i++)
                {
                    if (i > 0) sb.Append("\n\n");
                    _starts.Add(sb.Length);
                    sb.Append(Sections[i].Title);
                    sb.Append("\n");
                    sb.Append(Sections[i].Body);
                    sb.Append("\n");
                }
                _text.Text = sb.ToString();
                // Заголовки — крупнее и темнее (единожды при построении).
                using var hf = new Font("Segoe UI Semibold", 11F);
                foreach (int st in _starts)
                {
                    try
                    {
                        int end = _text.Text.IndexOf('\n', st);
                        if (end < 0) end = _text.Text.Length;
                        _text.Select(st, end - st);
                        _text.SelectionFont = hf;
                        _text.SelectionColor = ControlPaint.Dark(UiTheme.Accent, 0.5f);
                    }
                    catch { }
                }
                _text.Select(0, 0);
            }
            catch { }
        }
    }
